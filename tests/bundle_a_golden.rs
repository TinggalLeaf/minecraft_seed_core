    assert_eq!(out[0], BiomeId::Plains as i32);
    assert_eq!(out[1], BiomeId::DeepLukewarmOcean as i32);
    assert_eq!(out[2], BiomeId::FrozenOcean as i32); // land 为浅海时不升级
