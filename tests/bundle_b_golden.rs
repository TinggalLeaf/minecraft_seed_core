fn mc(v: u32) -> McVersion {
    match v {

        10 => McVersion::V1_7,
        15 => McVersion::V1_12,
        16 => McVersion::V1_13,
        17 => McVersion::V1_14,
        20 => McVersion::V1_16,
        21 => McVersion::V1_17,
        22 => McVersion::V1_18,
        24 => McVersion::V1_19,
        25 => McVersion::V1_20,
        28 => McVersion::V1_21,
        _ => panic!("bad mc"),
    }
}

fn stype(v: u32) -> StructureType {
    match v {

        1 => StructureType::DesertPyramid,
        2 => StructureType::JungleTemple,
        3 => StructureType::SwampHut,
        9 => StructureType::Mansion,
        _ => panic!("bad stype"),
    }
}

