fn mc(n: i32) -> McVersion {
    // C 侧 MC_UNDEF=0，故 B1_7=1 … 1.6=9。
    match n {
        1 => McVersion::B1_7,
        2 => McVersion::B1_8,
        3 => McVersion::V1_0,
        4 => McVersion::V1_1,
        5 => McVersion::V1_2,
        6 => McVersion::V1_3,
        7 => McVersion::V1_4,
        8 => McVersion::V1_5,
        9 => McVersion::V1_6,
        _ => panic!("未知版本号 {n}"),
    }
}

