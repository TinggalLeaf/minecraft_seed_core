//! 群系需求集合（对齐网站 api.wasm  解析的需求掩码，bytes 184..199）。
//!
//! 网站 find_biomes 的群系解析把每个请求 id 展开为 128 位需求掩码：
//! word1（bytes 184..191）覆盖 id 0..127（位 id & 63），word2（bytes
//! 192..199）覆盖 id 128+（位 (id-128) & 63）。区域匹配要求需求位全部
