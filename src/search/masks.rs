/// 单 id 的需求掩码。
pub fn req_mask(id: i32) -> (u64, u64) {
    for &(i, w) in D_MASKS {
        if i == id {
            return (
                (w[0] as u64) | ((w[1] as u64) << 32),
                (w[2] as u64) | ((w[3] as u64) << 32),
            );
        }
    }
    (0, 0)
}

impl BiomeSet {
    /// 解析请求 id 列表（各 id 掩码取并集，f_uc 语义）。
    pub fn parse(ids: &[i32]) -> BiomeSet {
        let mut set = BiomeSet::default();
        for &id in ids {
            let (w1, w2) = req_mask(id);
            set.req1 |= w1;
            set.req2 |= w2;
        }
        set
    }

    /// 区域两个字是否满足全部需求。
    #[inline]
    pub fn matches(&self, m1: u64, m2: u64) -> bool {
        (m1 & self.req1) == self.req1 && (m2 & self.req2) == self.req2
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn basic_masks() {
        assert_eq!(req_mask(1).0 & 2, 2);        // plains → bit 1
        assert_eq!(req_mask(7).0 & 128, 128);    // river → bit 7
        assert_eq!(req_mask(44).0 & (1 << 44), 1 << 44);
        assert_eq!(req_mask(129).1 & 2, 2);      // sunflower_plains → word2 bit 1
    }
}
