#[test]
fn areas_match_c() {
    for &(v, seed, scale, x, z, sx, sz, y, sy, expect) in AREA_CASES {
        let g = Generator::new(mc(v)).with_seed(Dimension::Overworld, seed as u64);
        let got = g.gen_biomes(Range::new(scale, x, z, sx, sz).with_y(y, sy));
        assert_eq!(
            biome_ids(&got),
            expect,
            "mc {v} seed {seed} scale {scale} @{x},{z}"
        );
    }
}

#[test]
fn intermediate_layers_match_c() {
    for &(v, seed, layer, expect) in LAYER_CASES {
        let mut ls = LayerStack::new(mc(v), false);
        ls.set_world_seed(seed as u64);
        let got = ls.gen_area(layer as usize, -4, -4, 8, 8);
        assert_eq!(got, expect, "mc {v} seed {seed} layer {layer:?}");
    }
}

