/// y == 0.0 快路径使用的缓存字段应与 b 的整数/小数部分一致，
/// 且 t2 等价于对 b 的小数部分重新计算 fade。
#[test]
fn y_zero_cache_consistent_with_b() {
    for &(seed, _, bb, _, h2, d2, t2, _) in JAVA_INIT {
        let mut rng = JavaRandom::new(seed);
        let n = PerlinNoise::new_java(&mut rng);
        let bval = f64::from_bits(bb);
        let i2 = bval.floor();
        let frac = bval - i2;
        assert_eq!(n.h2, h2, "seed {seed}");
        assert_eq!(n.d2.to_bits(), d2, "seed {seed}");
        assert_eq!(n.d2, frac, "seed {seed}");
        assert_eq!(n.t2.to_bits(), t2, "seed {seed}");
        let f = frac * frac * frac * (frac * (frac * 6.0 - 15.0) + 10.0);
        assert_eq!(n.t2, f, "seed {seed}");
    }
}
